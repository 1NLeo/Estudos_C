#include <stdio.h>

int main () {

    // Format specifiers

    printf ("Hello World!\n");

    printf ("Integer number: %d \n", 10);

    printf ("Float number: %f\n", 3.14159265);

    printf ("Float numbers with two decimal places: %.2f \n", 3.14159265);

    printf ("Alphanumeric character: %c\n", 'a'); // single quotation marks to only one character 

    printf ("Sequence of alphanumeric characters: %s\n", "Testing");


    return 0;
}